const colors = ["0f172a", "1f2937", "334155", "3f3f46", "292524", "7c2d12", "7f1d1d", "14532d"];

const imageUrlFor = ({brand, model, index}) => {
    const text = encodeURIComponent(`${brand} ${model}`);
    const color = colors[index % colors.length];
    return `https://placehold.co/1200x800/${color}/ffffff.jpg?text=${text}`;
};

export const buildSeedFleet = () => catalog.map((item, index) => {
    const [brand, model, year, category, seating_capacity, fuel_type, transmission, pricePerDay] = item;
    const location = locations[index % locations.length];
    return {
        brand,
        model,
        image: imageUrlFor({brand, model, index}),
        year,
        category,
        seating_capacity,
        fuel_type,
        transmission,
        pricePerDay,
        location: location.name,
        coordinates: {lat: location.lat, lng: location.lng},
        description: `${year} ${brand} ${model} ${category} with ${transmission.toLowerCase()} transmission, ${fuel_type.toLowerCase()} power, ${seating_capacity} seats, and ${location.name} pickup.`,
        isAvaliable: true
    };
});
